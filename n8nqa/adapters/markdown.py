"""Adapter: ReportData / findings -> Markdown text. Formatting only; every number comes in."""
from __future__ import annotations

from typing import List

from ..application.report import ReportData, StressResult
from ..domain.model import Finding
from ..domain.simulation import Metrics


def _pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def _counts(c) -> str:
    return ", ".join(f"{v} {k}" for k, v in c.items() if v)


def findings_text(findings: List[Finding]) -> str:
    lines = []
    for i, f in enumerate(findings, 1):
        where = f" [{', '.join(f.nodes)}]" if f.nodes else ""
        lines.append(f"F{i} {f.severity.label.upper():8} {f.rule_id}{where}\n    {f.evidence}")
    return "\n".join(lines) if lines else "No findings."


def _metric_rows(b: Metrics, a: Metrics) -> List[str]:
    rows = [
        ("Leads recorded exactly once", f"{b.recorded_exactly_once} / {b.unique_events} "
         f"({_pct(b.success_rate)})", f"{a.recorded_exactly_once} / {a.unique_events} "
         f"({_pct(a.success_rate)})"),
        ("Duplicate rows written", b.duplicate_rows, a.duplicate_rows),
        ("Leads lost with no alert", b.silent_losses, a.silent_losses),
        ("Leads parked in dead letter + alert sent", b.alerted, a.alerted),
        ("Redeliveries dropped by dedupe", b.skipped_duplicates, a.skipped_duplicates),
        ("LLM calls made", b.llm_calls, a.llm_calls),
        ("Processing time p50 (simulated ms)", b.p50_latency_ms, a.p50_latency_ms),
        ("Processing time p95 (simulated ms)", b.p95_latency_ms, a.p95_latency_ms),
    ]
    return [f"| {name} | {bv} | {av} |" for name, bv, av in rows]


RUNBOOK = """\
**What normal looks like.** The `Dead letter` sheet is empty and `#lead-intake-alerts`
is quiet. Every form submission becomes exactly one row in `Leads`, keyed by `event_id`.

**When an alert fires.**
1. Open the `Dead letter` sheet and find the row for the `event_id` in the alert.
2. Read `reason`:
   - `401` / `invalid api key` -> the OpenAI credential was revoked or rotated. Update it
     in n8n -> Credentials -> *OpenAI (credential store)*. No workflow edit needed.
   - `429` / `rate limit` -> too many parallel calls. Lower
     `N8N_CONCURRENCY_PRODUCTION_LIMIT` (or worker `--concurrency`) and replay.
   - `timeout` -> provider incident. Check the provider status page, replay later.
   - `label not allowed: ...` -> the model answered outside the label set. Label the lead
     by hand in `Leads`, or replay after tightening the prompt.
3. Replay: re-send the original `payload` from the dead-letter row to the webhook with
   the header `X-Replay: r1` (use `r2`, `r3` for later attempts). The replay header lets
   the event past the dedupe step; the upsert on `event_id` still keeps one row per lead.
4. Mark the dead-letter row `resolved` with the date.

**Changing the workflow.** Export the JSON before and after every change and keep both
in version control. Re-run the audit (`python -m n8nqa audit <file>`) and expect zero
critical/high findings before activating.

**Rotating the API key.** Create the new key, paste it into the n8n credential, run one
test submission, then revoke the old key. Keys never go into node parameters."""


def _stress_section(r: StressResult, before_name: str, after_name: str) -> List[str]:
    s, b, a = r.scenario, r.before, r.after
    lines = [f"#### {r.label}", "",
             f"{s.events} unique leads per run arriving within {int(s.burst_window_ms)} ms, "
             f"{s.redeliveries_per_run} of them redelivered 0.1-5 s later "
             f"({_pct(s.duplicate_ratio)}), each LLM attempt failing with probability "
             f"{s.llm_failure_ratio}, {s.runs} runs, seed {s.seed}. Totals across all runs:", "",
             f"| Metric | {before_name} | {after_name} |", "|---|---|---|"]
    lines.extend(_metric_rows(b, a))
    lines.append("")
    return lines


def render_report(d: ReportData) -> str:
    a_res = d.stress[0]
    s, b, a = a_res.scenario, a_res.before, a_res.after
    out: List[str] = []
    w = out.append
    w("# Workflow QA Report: Lead intake (webhook -> LLM -> Google Sheets)")
    w("")
    w(f"- **Report date:** {d.report_date}")
    w(f"- **Workflow audited:** `{d.workflow_file}` ({d.node_count} nodes, \"{d.workflow_name}\")")
    w("- **Turnaround:** written report within 48 hours of receiving the workflow export")
    w("- **Communication:** async, written only (email)")
    w("- **Method:** static review of the exported JSON + reproducible stress simulation")
    w("")
    w("> **This is a public sample.** The workflow is fictional and was written for this")
    w("> repository. There is no customer, no real data and no real key (the one key in the")
    w("> JSON is a planted placeholder). Every number in this report is generated by")
    w("> `python -m n8nqa report`; the test suite fails if this file and the generated output")
    w("> differ.")
    w("")
    w("## 1. Summary")
    w("")
    w(f"- **{len(d.findings)} findings:** {_counts(d.before_counts)}. After the fixes in "
      f"`lead-intake.fixed.json`: {sum(d.after_counts.values())} findings.")
    w(f"- **{a_res.label}, as delivered:** {s.events} leads per burst, "
      f"{_pct(s.duplicate_ratio)} redelivered by the sender, {_pct(s.llm_failure_ratio)} of "
      f"LLM calls failing, {s.runs} seeded runs. {_pct(b.success_rate)} of leads were "
      f"recorded exactly once; {b.duplicate_rows} duplicate rows were written and "
      f"{b.silent_losses} leads were lost without any alert.")
    w(f"- **Same scenario with the fixes:** {_pct(a.success_rate)} recorded exactly once, "
      f"{a.duplicate_rows} duplicate rows, {a.silent_losses} silent losses.")
    for r in d.stress[1:]:
        w(f"- **{r.label}** ({_pct(r.scenario.llm_failure_ratio)} of LLM calls failing): "
          f"as delivered {r.before.silent_losses} leads were lost silently; with the fixes "
          f"{r.after.silent_losses} were lost silently and {r.after.alerted} were parked in "
          f"the dead-letter sheet with an alert, ready to replay.")
    w("- **Fix first:** " + "; ".join(f"F{i} {f.title}" for i, f in enumerate(d.findings[:3], 1)) + ".")
    w("")
    w("## 2. Findings (most severe first)")
    w("")
    for i, f in enumerate(d.findings, 1):
        w(f"### F{i} · {f.severity.label.upper()} · {f.title}")
        w("")
        w(f"- **Rule:** `{f.rule_id}`")
        if f.nodes:
            w(f"- **Nodes:** {', '.join(f'`{n}`' for n in f.nodes)}")
        w(f"- **Evidence:** {f.evidence}")
        w(f"- **Impact:** {f.impact}")
        w(f"- **Fix:** {f.fix}")
        w("")
    w("## 3. Before / after")
    w("")
    w("### Static audit")
    w("")
    w("| Severity | Before (`lead-intake.json`) | After (`lead-intake.fixed.json`) |")
    w("|---|---|---|")
    for k in d.before_counts:
        w(f"| {k} | {d.before_counts[k]} | {d.after_counts[k]} |")
    w("")
    w("### Stress simulation")
    w("")
    w(f"Pipeline settings simulated. **Before:** {d.before_cfg.max_tries} try, no dedupe, "
      f"no alert. **After:** {d.after_cfg.max_tries} tries with "
      f"{int(d.after_cfg.retry_wait_ms)} ms between tries, idempotency key claimed on "
      "arrival, failures routed to dead letter + alert.")
    w("")
    for r in d.stress:
        out.extend(_stress_section(r, d.before_cfg.name, d.after_cfg.name))
    w("**What the simulation is and is not.** It replays the same deliveries and the same")
    w("failure rolls through both pipeline configs, so the difference is the pipeline, not")
    w("luck. Latency is a model (LLM attempt ~N(900, 300) ms, sheet write ~N(150, 30) ms),")
    w("useful for comparing before and after, not as a production forecast. Retries make")
    w("some leads slower (a lead that waits 1 s and retries is slower than a lead that is")
    w("dropped), which is why p95 moves. Provider rate limits (429) and concurrency caps")
    w("are not simulated; that risk is covered by the static finding.")
    w("")
    w("## 4. Fix checklist (in order)")
    w("")
    for i, f in enumerate(d.findings, 1):
        w(f"- [ ] **F{i}** `{f.rule_id}`: {f.fix.split('. ')[0].rstrip('.')}.")
    w("")
    w("The fixed workflow is included as `workflow/lead-intake.fixed.json` so every change")
    w("above can be diffed node by node against the original.")
    w("")
    w("## 5. Runbook")
    w("")
    w(RUNBOOK)
    w("")
    return "\n".join(out)
